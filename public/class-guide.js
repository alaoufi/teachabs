const esc = s => String(s).replace(/[&<>"']/g, c => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'})[c]);
const inline = s => esc(s).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/`(.+?)`/g, '<kbd>$1</kbd>');

export function guideHTML() {
  return `<article class="guide" dir="rtl"><div class="section-head welcome-panel"><div class="eyebrow">الحصة الجماعية</div><h1>${GUIDE_TITLE}</h1><p>${esc(GUIDE_INTRO)}</p></div>
  <nav class="guide-toc" aria-label="أقسام الدليل"><ol>${GUIDE.map(s => `<li><a href="#${s.id}">${esc(s.title)}</a></li>`).join('')}</ol></nav>
  ${GUIDE.map((s, i) => `<section class="guide-section panel" id="${s.id}"><h2><span>${i + 1}</span>${esc(s.title)}</h2><ul>${s.items.map(x => `<li>${inline(x)}</li>`).join('')}</ul></section>`).join('\n  ')}
  <p class="guide-foot"><a class="outline" href="/teach/plans">دروسي</a> <a class="textlink" href="/join">دخول طالب</a> <a class="textlink" href="/demo">أقسام التجربة</a></p></article>`;
}

export function guideMarkdown() {
  return `# ${GUIDE_TITLE}\n\n${GUIDE_INTRO}\n\n` + GUIDE.map((s, i) => `## ${i + 1}. ${s.title}\n\n${s.items.map(x => '- ' + x).join('\n')}\n`).join('\n') +
    '\n---\nهذا الملف مولَّد من `public/class-guide.js`، وهو المصدر نفسه لصفحة `/guide` داخل التطبيق. عدّل المصدر ثم أعد التوليد.\n';
}
